-- Gestión industrial › TPS › Obiras
-- Registro de problemas (obiras) con sus repeticiones, acciones (gestión de
-- anormalidades y acciones definitivas) y archivos adjuntos.

begin;

-- ── Tablas ─────────────────────────────────────────────────────────────────

-- El id es el número correlativo que ve el usuario ("ID" en el tablero).
-- "by default" permite importar obiras históricas conservando su número
-- (después de importar hay que ajustar la secuencia con setval).
create table public."Obiras" (
  id                 bigint generated by default as identity,
  sector             text not null,
  ubicacion          text not null,
  fecha_ocurrencia   date not null,
  responsable        text,
  titulo             text not null,
  detalle            text,
  etapa_constructiva text not null,
  cantidad           numeric not null,
  unidad             text not null,
  estado             text not null default 'Sin iniciar',
  accion_inmediata   text,
  causa_raiz         text,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  created_by         uuid default auth.uid(),
  constraint "Obiras_pkey" primary key (id),
  constraint "Obiras_sector_check"   check (sector = any (array['Locaciones'::text, 'Obras Públicas'::text])),
  constraint "Obiras_unidad_check"   check (unidad = any (array['Horas'::text, 'Días'::text, 'Meses'::text])),
  constraint "Obiras_estado_check"   check (estado = any (array['Sin iniciar'::text, 'En gestión'::text, 'Finalizada'::text])),
  constraint "Obiras_cantidad_check" check (cantidad >= 0::numeric),
  constraint "Obiras_created_by_fkey" foreign key (created_by) references auth.users(id) on delete set null
);

create table public."ObirasRepeticiones" (
  id          uuid not null default gen_random_uuid(),
  obira_id    bigint not null,
  fecha       date not null,
  cantidad    numeric,
  ubicacion   text,
  comentarios text,
  created_at  timestamptz not null default now(),
  constraint "ObirasRepeticiones_pkey" primary key (id),
  constraint "ObirasRepeticiones_cantidad_check" check (cantidad >= 0::numeric),
  constraint "ObirasRepeticiones_obira_id_fkey" foreign key (obira_id)
    references public."Obiras"(id) on delete cascade
);

-- tipo 'anormalidad': gestión de anormalidades (minimizar el impacto).
-- tipo 'definitiva':  acciones definitivas / contramedidas (eliminar la causa raíz).
-- status es texto libre a propósito: la lista de opciones vive en src/obiras.js.
create table public."ObirasAcciones" (
  id          uuid not null default gen_random_uuid(),
  obira_id    bigint not null,
  tipo        text not null,
  descripcion text not null,
  fecha       date,
  responsable text,
  status      text,
  orden       integer not null default 0,
  created_at  timestamptz not null default now(),
  constraint "ObirasAcciones_pkey" primary key (id),
  constraint "ObirasAcciones_tipo_check" check (tipo = any (array['anormalidad'::text, 'definitiva'::text])),
  constraint "ObirasAcciones_obira_id_fkey" foreign key (obira_id)
    references public."Obiras"(id) on delete cascade
);

-- Los archivos viven en el bucket privado "obiras-archivos"; path es la ruta
-- dentro del bucket ({obira_id}/{timestamp}-{nombre}).
create table public."ObirasArchivos" (
  id         uuid not null default gen_random_uuid(),
  obira_id   bigint not null,
  path       text not null,
  nombre     text not null,
  tamano     bigint,
  created_at timestamptz not null default now(),
  constraint "ObirasArchivos_pkey" primary key (id),
  constraint "ObirasArchivos_obira_id_fkey" foreign key (obira_id)
    references public."Obiras"(id) on delete cascade
);

-- Catálogo de ubicaciones que mantiene un admin. Se ofrecen como sugerencia:
-- el campo ubicación de la obira sigue siendo de texto libre.
create table public."ObirasUbicaciones" (
  id         uuid not null default gen_random_uuid(),
  nombre     text not null,
  created_at timestamptz not null default now(),
  constraint "ObirasUbicaciones_pkey" primary key (id),
  constraint "ObirasUbicaciones_nombre_key" unique (nombre)
);

-- ── Índices ────────────────────────────────────────────────────────────────

create index "ObirasRepeticiones_obira_id_idx" on public."ObirasRepeticiones" using btree (obira_id);
create index "ObirasAcciones_obira_id_idx"     on public."ObirasAcciones"     using btree (obira_id);
create index "ObirasArchivos_obira_id_idx"     on public."ObirasArchivos"     using btree (obira_id);

-- ── Permisos y RLS ─────────────────────────────────────────────────────────

grant select, insert, update, delete on table
  public."Obiras", public."ObirasRepeticiones", public."ObirasAcciones",
  public."ObirasArchivos", public."ObirasUbicaciones"
to authenticated, service_role;

alter table public."Obiras"             enable row level security;
alter table public."ObirasRepeticiones" enable row level security;
alter table public."ObirasAcciones"     enable row level security;
alter table public."ObirasArchivos"     enable row level security;
alter table public."ObirasUbicaciones"  enable row level security;

-- Cualquier usuario autenticado carga y edita obiras; borrar una obira es solo de admins.
create policy authenticated_select_obiras on public."Obiras" for select to authenticated using (true);
create policy authenticated_insert_obiras on public."Obiras" for insert to authenticated with check (true);
create policy authenticated_update_obiras on public."Obiras" for update to authenticated using (true) with check (true);
create policy admins_delete_obiras on public."Obiras" for delete to authenticated
  using (exists (select 1 from profiles where profiles.id = auth.uid() and profiles.rol = 'admin'::text));

create policy authenticated_all_obiras_repeticiones on public."ObirasRepeticiones" for all to authenticated using (true) with check (true);
create policy authenticated_all_obiras_acciones     on public."ObirasAcciones"     for all to authenticated using (true) with check (true);
create policy authenticated_all_obiras_archivos     on public."ObirasArchivos"     for all to authenticated using (true) with check (true);

create policy select_obiras_ubicaciones on public."ObirasUbicaciones" for select to authenticated using (true);
create policy admins_manage_obiras_ubicaciones on public."ObirasUbicaciones" for all to authenticated
  using (exists (select 1 from profiles where profiles.id = auth.uid() and profiles.rol = 'admin'::text))
  with check (exists (select 1 from profiles where profiles.id = auth.uid() and profiles.rol = 'admin'::text));

-- ── Guardado atómico ───────────────────────────────────────────────────────
-- Crea o actualiza una obira junto con sus repeticiones y acciones en una sola
-- transacción. Las listas reemplazan a las existentes (se conservan los id que
-- vengan informados). Corre con los permisos del usuario (security invoker).
create or replace function public.guardar_obira(p_obira jsonb, p_repeticiones jsonb, p_acciones jsonb)
returns bigint
language plpgsql
security invoker
set search_path to 'public'
as $function$
declare
  v_id bigint := nullif(p_obira->>'id', '')::bigint;
begin
  if v_id is null then
    insert into "Obiras" (
      sector, ubicacion, fecha_ocurrencia, responsable, titulo, detalle,
      etapa_constructiva, cantidad, unidad, estado, accion_inmediata, causa_raiz
    ) values (
      p_obira->>'sector', nullif(trim(p_obira->>'ubicacion'), ''), (p_obira->>'fecha_ocurrencia')::date,
      nullif(trim(p_obira->>'responsable'), ''), nullif(trim(p_obira->>'titulo'), ''), nullif(trim(p_obira->>'detalle'), ''),
      nullif(trim(p_obira->>'etapa_constructiva'), ''), (p_obira->>'cantidad')::numeric, p_obira->>'unidad',
      coalesce(p_obira->>'estado', 'Sin iniciar'), nullif(trim(p_obira->>'accion_inmediata'), ''), nullif(trim(p_obira->>'causa_raiz'), '')
    )
    returning id into v_id;
  else
    update "Obiras" set
      sector             = p_obira->>'sector',
      ubicacion          = nullif(trim(p_obira->>'ubicacion'), ''),
      fecha_ocurrencia   = (p_obira->>'fecha_ocurrencia')::date,
      responsable        = nullif(trim(p_obira->>'responsable'), ''),
      titulo             = nullif(trim(p_obira->>'titulo'), ''),
      detalle            = nullif(trim(p_obira->>'detalle'), ''),
      etapa_constructiva = nullif(trim(p_obira->>'etapa_constructiva'), ''),
      cantidad           = (p_obira->>'cantidad')::numeric,
      unidad             = p_obira->>'unidad',
      estado             = coalesce(p_obira->>'estado', 'Sin iniciar'),
      accion_inmediata   = nullif(trim(p_obira->>'accion_inmediata'), ''),
      causa_raiz         = nullif(trim(p_obira->>'causa_raiz'), ''),
      updated_at         = now()
    where id = v_id;
    if not found then
      raise exception 'La obira % no existe', v_id;
    end if;
  end if;

  delete from "ObirasRepeticiones" where obira_id = v_id;
  insert into "ObirasRepeticiones" (id, obira_id, fecha, cantidad, ubicacion, comentarios)
  select coalesce(nullif(r->>'id', '')::uuid, gen_random_uuid()), v_id,
         (r->>'fecha')::date, nullif(r->>'cantidad', '')::numeric,
         nullif(trim(r->>'ubicacion'), ''), nullif(trim(r->>'comentarios'), '')
  from jsonb_array_elements(coalesce(p_repeticiones, '[]'::jsonb)) as t(r);

  delete from "ObirasAcciones" where obira_id = v_id;
  insert into "ObirasAcciones" (id, obira_id, tipo, descripcion, fecha, responsable, status, orden)
  select coalesce(nullif(a->>'id', '')::uuid, gen_random_uuid()), v_id,
         a->>'tipo', nullif(trim(a->>'descripcion'), ''), nullif(a->>'fecha', '')::date,
         nullif(trim(a->>'responsable'), ''), nullif(trim(a->>'status'), ''), ord::integer
  from jsonb_array_elements(coalesce(p_acciones, '[]'::jsonb)) with ordinality as t(a, ord);

  return v_id;
end;
$function$;

revoke all on function public.guardar_obira(jsonb, jsonb, jsonb) from public, anon;
grant execute on function public.guardar_obira(jsonb, jsonb, jsonb) to authenticated, service_role;

-- ── Storage ────────────────────────────────────────────────────────────────

insert into storage.buckets (id, name, public) values ('obiras-archivos', 'obiras-archivos', false);

create policy "Obiras archivos: lectura autenticados" on storage.objects for select to authenticated
  using (bucket_id = 'obiras-archivos'::text);
create policy "Obiras archivos: subida autenticados" on storage.objects for insert to authenticated
  with check (bucket_id = 'obiras-archivos'::text);
create policy "Obiras archivos: borrado autenticados" on storage.objects for delete to authenticated
  using (bucket_id = 'obiras-archivos'::text);

commit;
