-- Gestión industrial › Toyota Well › Locaciones / Obras Públicas
-- Cronograma de implementación del modelo (importado una vez desde MS Project;
-- desde entonces el avance se actualiza en la app). Las fechas inicio/fin son la
-- línea base (plan ideal); inicio_real/fin_real/avance son la ejecución. Cada
-- actualización de avance queda en ToyotaWellAvances, con la justificación del
-- desvío cuando la tarea está atrasada.

begin;

-- ── Tablas ─────────────────────────────────────────────────────────────────

create table public."ToyotaWellTareas" (
  id           bigint generated by default as identity primary key,
  sector       text    not null check (sector in ('Locaciones', 'Obras Públicas')),
  parent_id    bigint  references public."ToyotaWellTareas"(id) on delete cascade,
  -- Posición dentro del sector; es el "Id" que se ve en la tabla (como en Project).
  orden        integer not null,
  nombre       text    not null check (btrim(nombre) <> ''),
  inicio       date,
  fin          date,
  avance       smallint not null default 0 check (avance between 0 and 100),
  inicio_real  date,
  fin_real     date,
  -- Tareas que tienen que terminar antes de que esta empiece (vínculo fin-comienzo).
  predecesoras bigint[] not null default '{}',
  notas        text,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  updated_by   uuid default auth.uid() references public.profiles(id) on delete set null,
  constraint "ToyotaWellTareas_plan_check"  check (inicio is null or fin is null or fin >= inicio),
  constraint "ToyotaWellTareas_real_check"  check (inicio_real is null or fin_real is null or fin_real >= inicio_real),
  constraint "ToyotaWellTareas_orden_key"   unique (sector, orden) deferrable initially deferred
);

create table public."ToyotaWellAvances" (
  id            bigint generated always as identity primary key,
  tarea_id      bigint   not null references public."ToyotaWellTareas"(id) on delete cascade,
  -- Fecha a la que corresponde el avance informado (para la curva real).
  fecha         date     not null default current_date,
  avance        smallint not null check (avance between 0 and 100),
  inicio_real   date,
  fin_real      date,
  justificacion text,
  origen        text     not null default 'app' check (origen in ('app', 'importacion')),
  created_at    timestamptz not null default now(),
  created_by    uuid default auth.uid() references public.profiles(id) on delete set null
);

create index "ToyotaWellTareas_parent_id_idx"  on public."ToyotaWellTareas"  using btree (parent_id);
create index "ToyotaWellAvances_tarea_id_idx"  on public."ToyotaWellAvances" using btree (tarea_id);

-- ── Trigger: auditoría y protección de la línea base ───────────────────────
-- La línea base (fechas del plan, nombre, estructura, predecesoras) solo la
-- cambia un admin, para que los desvíos no se "corrijan" moviendo el plan.
-- Sin usuario (SQL editor / service role) se permite, para importaciones.
create or replace function public.toyota_well_tareas_before_update()
returns trigger
language plpgsql
security invoker
set search_path to ''
as $function$
begin
  if auth.uid() is not null
     and (new.inicio, new.fin, new.nombre, new.parent_id, new.orden, new.predecesoras, new.sector)
         is distinct from (old.inicio, old.fin, old.nombre, old.parent_id, old.orden, old.predecesoras, old.sector)
     and not exists (select 1 from public.profiles p where p.id = auth.uid() and p.rol = 'admin') then
    raise exception 'Solo un administrador puede modificar el plan (línea base) del cronograma'
      using errcode = '42501';
  end if;
  new.updated_at := now();
  new.updated_by := auth.uid();
  return new;
end;
$function$;

create trigger toyota_well_tareas_before_update
before update on public."ToyotaWellTareas"
for each row execute function public.toyota_well_tareas_before_update();

-- ── Registrar avance ───────────────────────────────────────────────────────
-- Actualiza el avance y las fechas reales de una tarea y deja el registro en el
-- historial, en una sola transacción. La justificación es obligatoria cuando la
-- tarea está atrasada respecto de su línea base (empezó o terminó después de lo
-- planificado, o a la fecha del avance ya debería haber empezado o terminado).
create or replace function public.registrar_avance_toyota_well(
  p_tarea_id      bigint,
  p_avance        integer,
  p_inicio_real   date,
  p_fin_real      date,
  p_fecha         date,
  p_justificacion text
)
returns bigint
language plpgsql
security invoker
set search_path to 'public'
as $function$
declare
  t       "ToyotaWellTareas";
  v_fecha date := coalesce(p_fecha, current_date);
  v_just  text := nullif(btrim(p_justificacion), '');
  v_id    bigint;
begin
  select * into t from "ToyotaWellTareas" where id = p_tarea_id for update;
  if not found then
    raise exception 'La tarea % no existe', p_tarea_id using errcode = 'P0002';
  end if;
  if exists (select 1 from "ToyotaWellTareas" h where h.parent_id = p_tarea_id) then
    raise exception 'El avance de una tarea resumen se calcula a partir de sus subtareas';
  end if;
  if p_avance is null or p_avance < 0 or p_avance > 100 then
    raise exception 'El avance tiene que estar entre 0 y 100';
  end if;
  if v_fecha > current_date then
    raise exception 'La fecha del avance no puede ser futura';
  end if;
  if p_avance > 0 and p_inicio_real is null then
    raise exception 'Indicá la fecha real de comienzo';
  end if;
  if p_avance = 100 and p_fin_real is null then
    raise exception 'Indicá la fecha real de finalización';
  end if;
  if p_avance < 100 and p_fin_real is not null then
    raise exception 'Una tarea con fecha real de fin tiene que estar al 100 %%';
  end if;
  if p_inicio_real > current_date or p_fin_real > current_date then
    raise exception 'Las fechas reales no pueden ser futuras';
  end if;

  if v_just is null and (
       (t.inicio is not null and coalesce(p_inicio_real, v_fecha) > t.inicio)
    or (t.fin    is not null and coalesce(p_fin_real,    v_fecha) > t.fin)
  ) then
    raise exception 'La tarea está atrasada respecto del plan: justificá el desvío';
  end if;

  update "ToyotaWellTareas"
     set avance = p_avance, inicio_real = p_inicio_real, fin_real = p_fin_real
   where id = p_tarea_id;

  insert into "ToyotaWellAvances" (tarea_id, fecha, avance, inicio_real, fin_real, justificacion)
  values (p_tarea_id, v_fecha, p_avance, p_inicio_real, p_fin_real, v_just)
  returning id into v_id;

  return v_id;
end;
$function$;

revoke all on function public.registrar_avance_toyota_well(bigint, integer, date, date, date, text) from public, anon;
grant execute on function public.registrar_avance_toyota_well(bigint, integer, date, date, date, text) to authenticated, service_role;

-- ── Permisos y RLS ─────────────────────────────────────────────────────────

revoke all on table public."ToyotaWellTareas", public."ToyotaWellAvances" from anon;
grant select, insert, update, delete on table public."ToyotaWellTareas" to authenticated, service_role;
grant select, insert on table public."ToyotaWellAvances" to authenticated;
grant select, insert, update, delete on table public."ToyotaWellAvances" to service_role;

alter table public."ToyotaWellTareas"  enable row level security;
alter table public."ToyotaWellAvances" enable row level security;

-- Todos los usuarios ven el cronograma y actualizan avance y notas; crear o
-- borrar tareas es de admins (el trigger además protege la línea base).
create policy authenticated_select_tw_tareas on public."ToyotaWellTareas" for select to authenticated using (true);
create policy authenticated_update_tw_tareas on public."ToyotaWellTareas" for update to authenticated using (true) with check (true);
create policy admins_insert_tw_tareas on public."ToyotaWellTareas" for insert to authenticated
  with check (exists (select 1 from profiles where profiles.id = auth.uid() and profiles.rol = 'admin'::text));
create policy admins_delete_tw_tareas on public."ToyotaWellTareas" for delete to authenticated
  using (exists (select 1 from profiles where profiles.id = auth.uid() and profiles.rol = 'admin'::text));

-- El historial no se edita ni se borra: cada registro queda a nombre de quien lo cargó.
create policy authenticated_select_tw_avances on public."ToyotaWellAvances" for select to authenticated using (true);
create policy authenticated_insert_tw_avances on public."ToyotaWellAvances" for insert to authenticated
  with check (created_by = auth.uid() and origen = 'app');

commit;
